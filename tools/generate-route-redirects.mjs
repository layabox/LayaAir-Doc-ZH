import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, '_book');
const base = '/3.x/doc';

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(file, out);
    else out.push(file);
  }
  return out;
}

const redirects = [];
for (const file of walk(dist)) {
  if (path.basename(file).toLowerCase() !== 'index.html') continue;
  const dir = path.relative(dist, path.dirname(file)).replace(/\\/g, '/');
  if (!dir || dir === dir.toLowerCase()) continue;
  const target = `${base}/${dir}/`;
  redirects.push({ source: target.toLowerCase(), target });
}

// 较长路径优先，避免父级 Redirect 的前缀匹配抢先处理子页面。
redirects.sort((a, b) => b.source.length - a.source.length || a.source.localeCompare(b.source));
const lines = [
  '# Generated by tools/generate-route-redirects.mjs. Do not edit manually.',
  '# Keep legacy lowercase URLs working on Linux/Apache deployments.',
  ...redirects.map(({ source, target }) => `Redirect 301 ${source} ${target}`),
  '',
];
fs.writeFileSync(path.join(dist, '.htaccess'), lines.join('\n'));
console.log(`已生成 ${redirects.length} 条旧版小写 URL 永久重定向。`);
